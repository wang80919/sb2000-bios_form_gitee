/** $1B 每多等一帧，耗用的模拟器帧数随之线性增加（实测约 1.5-3 倍，由 VBlank 标志的检测方式与开机方式决定），只核对增量在合理范围内 */
const waitCase = {
  id: 'kernel.1b.wait-scales',
  title: '$1B 等待 4 帧与 32 帧：多等的 28 帧，耗用的模拟器帧数增加 28 到 100',
  steps: [{ func: 0x1b, x: 4, maxFrames: 200 }, { func: 0x1b, x: 32, maxFrames: 400 }],
  finalCheck: (history) => {
    const delta = history[1].frames - history[0].frames;
    return delta >= 28 && delta <= 100 ? [] : [`增量 ${delta} 帧`];
  },
};

/** $25：映射页组 $0642 后调用 $0C/$0D 指向的地址；页组 $09 的 $8574 是 16 位除法（功能 $4B 的入口） */
const bankedCall = {
  id: 'kernel.25.call-banked',
  title: '$25 映射页组 $09 后调用 $8574（16 位除法）：100 ÷ 7 = 14 余 2，调用后返回',
  func: 0x25,
  mem: [[0x642, [0x09]], [0x0c, [0x74, 0x85]], [0x69a, [0x64, 0x00, 0x07]]],
  expect: [[0x69a, [0x0e, 0x00, 0x02]]],
  maxFrames: 60,
};

export const cases = [waitCase, bankedCall];
