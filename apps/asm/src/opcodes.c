/** 在银行 4 中查找官方助记符与寻址方式对应的机器码。 */
unsigned char asm_find_opcode(const char *mnemonic, unsigned char mode, unsigned char *code)
{
    unsigned char index;

    for (index = 0; index < sizeof(OPCODES) / sizeof(OPCODES[0]); ++index) {
        if (OPCODES[index].mode == mode && strcmp(OPCODES[index].mnemonic, mnemonic) == 0) {
            *code = OPCODES[index].code;
            return 1;
        }
    }
    return 0;
}

