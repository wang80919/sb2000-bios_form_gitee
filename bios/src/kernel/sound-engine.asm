    INY
    LDA SOUND_REG_SHADOW-2,Y
    BMI SOUND_WRITE_REG_ZP3
    LDA SOUND_TRACK_PTR_HI
    STA SOUND_REG_SHADOW,Y
    CMP SOUND_REG_SHADOW,Y
    BNE SOUND_WRITE_REG_ZP3
    RTS
; 作用：把 SOUND_TRACK_PTR_HI 作为要写的值，落入 SOUND_WRITE_REG。
; 调用者：SOUND_APPLY_PITCH、SOUND_APPLY_PITCH_BEND
SOUND_WRITE_REG_ZP3:
