; 作用：把 A 存入寄存器影子 SOUND_REG_SHADOW+Y，再经 SOUND_APU_STUB 写到 APU：音乐声道（X 小于 4）在对应的音效声道（SOUND_CHANNEL_FLAGS+4+X）在用时只更新影子；音效声道（X 不小于 4）的 APU 寄存器号取 Y 的低 4 位。
; 输入：A=要写的值，Y=寄存器影子偏移（4×声道号+寄存器号），X=声道号。
; 调用者：SOUND_CMD_STOP_CHANNEL、SOUND_ENVELOPE_RUN、SOUND_VOLUME_ENVELOPE、SOUND_KEY_OFF_CLEAR_VOLUME、SOUND_KEY_OFF_TRIANGLE、SOUND_APPLY_REG01、SOUND_APPLY_PITCH、SOUND_APPLY_NOTE_ON等 14 处
SOUND_WRITE_REG:
    STA SOUND_REG_SHADOW,Y
    CPX #$04
    BCS @fx_register
    LDA SOUND_CHANNEL_FLAGS+4,X
    BNE @return
    STY SOUND_APU_STUB+1
    BEQ @write
@fx_register:
    TYA
    AND #$0F
    STA SOUND_APU_STUB+1
@write:
    LDA SOUND_REG_SHADOW,Y
    JMP SOUND_APU_STUB
@return:
    RTS
; 作用：发声（SOUND_UPDATE_FLAGS 位 4）：SOUND_CHANNEL_FLAGS 位 7 已为 1 时直接返回；否则置位并写寄存器 2、3（SOUND_WRITE_REG23）：三角波寄存器 0 写 $81，音乐声道设包络阶段为 1，音效声道写出音量（SOUND_APPLY_LEVEL_WRITE）。
