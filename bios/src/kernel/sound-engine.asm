; 作用：命令 $CE、$CF 计数未到 0 时：从音轨取 16 位偏移，加上曲首地址（声道 0-3 用 SOUND_MUSIC_BASE_LO/HI，声道 4-7 用 SOUND_FX_BASE_LO/HI）作为新的音轨位置 SOUND_TRACK_PTR_LO/HI。
