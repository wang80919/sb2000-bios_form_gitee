SOUND_JUMP_TRACK:
    LDA (SOUND_TRACK_PTR_LO),Y
    PHA
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_TRACK_PTR_HI
    PLA
    STA SOUND_TRACK_PTR_LO
