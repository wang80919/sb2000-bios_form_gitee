    ASL A
    ASL A
    TAY
    LDA SOUND_REG_SHADOW,Y
    JSR SOUND_WRITE_REG
    INY
    LDA SOUND_REG_SHADOW,Y
    JMP SOUND_WRITE_REG
; 作用：按音符求出音高周期并写寄存器 2（SOUND_UPDATE_FLAGS 位 5）：噪声声道（3、7）按 SOUND_NOISE_PTR 指向的噪声表取 4 字节项改写噪声参数；音调声道按 SOUND_NOTE 查周期表 SOUND_PERIOD_LO/HI，再加 SOUND_PITCH_OFFSET（声道 0-2 还加颤音偏移 SOUND_VIBRATO_OFFSET）按 SOUND_PERIOD_LO_NEXT 插值。周期高字节只更新影子，寄存器 1（扫频）位 7 为 1 时才一并写到 APU（SOUND_WRITE_REG_ZP3）。
; 输入：X=声道号。
; 调用者：SOUND_FLUSH_CHANNEL
SOUND_APPLY_PITCH:
    TXA
    AND #$03
    CMP #$03
    BNE @tone
    CPX #$03
    BEQ @noise_table
    LDA SOUND_NOTE,X
@write_noise_period:
    PHA
    TXA
    ASL A
    ASL A
    TAY
    INY
    INY
    PLA
    JMP SOUND_WRITE_REG
@noise_table:
    LDA SOUND_NOISE_PTR_LO
    STA SOUND_TEMP0
    LDA SOUND_NOISE_PTR_HI
    STA SOUND_TEMP1
    LDA SOUND_NOTE,X
    ASL A
    ASL A
    TAY
    LDA (SOUND_TEMP0),Y
    STA SOUND_ENVELOPE_PTR_LO+2
    INY
    LDA (SOUND_TEMP0),Y
    STA SOUND_ENVELOPE_PTR_HI+2
    INY
    LDA (SOUND_TEMP0),Y
    JMP @write_noise_period
@tone:
    CPX #$04
    BCS @fx_channel
    LDA SOUND_VIBRATO_OFFSET,X
    BMI @negative_offset
    CLC
    ADC SOUND_PITCH_OFFSET,X
    STA SOUND_TEMP0
    LDA SOUND_NOTE,X
    ADC #$00
    JMP @lookup_period
@negative_offset:
    CLC
    ADC SOUND_PITCH_OFFSET,X
    STA SOUND_TEMP0
    LDA SOUND_NOTE,X
    SBC #$00
    JMP @lookup_period
@fx_channel:
    LDA SOUND_PITCH_OFFSET,X
    STA SOUND_TEMP0
    LDA SOUND_NOTE,X
@lookup_period:
    AND #$3F
    TAY
    LDA SOUND_PERIOD_LO,Y
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_PERIOD_HI,Y
    STA SOUND_TRACK_PTR_HI
    LDA SOUND_TEMP0
    BEQ @write_period
    LDA SOUND_TRACK_PTR_LO
    SEC
    SBC SOUND_PERIOD_LO_NEXT,Y
    STA SOUND_TEMP1
    JSR MUL8_HIGH
    LDA SOUND_TRACK_PTR_LO
    SEC
    SBC SOUND_TEMP0
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_TRACK_PTR_HI
    SBC #$00
    STA SOUND_TRACK_PTR_HI
@write_period:
    TXA
    ASL A
    ASL A
    TAY
    INY
    INY
    LDA SOUND_TRACK_PTR_LO
