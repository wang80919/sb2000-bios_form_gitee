; 作用：每帧声音更新的入口：SOUND_FLAGS 位 7 为 0 时直接返回；位 5（自动切歌）打开且位 6 为 0 时，SOUND_AUTO_COUNT 每帧减 1，减到 0 就把 SOUND_AUTO_RELOAD 存入 SOUND_NEXT_SONG 并调用 SOUND_PLAY_SONG；之后进入 SOUND_TICK。
; 调用者：NMI_HANDLER
NMI_SOUND_UPDATE:
    BIT SOUND_FLAGS
    BMI @enabled
    JMP SOUND_UPDATE_RETURN
@enabled:
    LDA SOUND_FLAGS
    AND #$20
    BEQ SOUND_TICK
    LDA SOUND_FLAGS
    AND #$40
    BNE SOUND_TICK
    DEC SOUND_AUTO_COUNT
    BNE SOUND_TICK
    LDA SOUND_AUTO_RELOAD
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
; 作用：每帧声音更新：先处理音效声道 7-4（时长倒计时、刷新寄存器），再处理音乐声道 3-0（颤音、刷新寄存器、包络）；按拍速 SOUND_TEMPO 累加到 SOUND_TEMPO_ACC，有进位时才处理音乐声道的时长。
; 输入：SOUND_PLAYING 为 0 时直接返回；SOUND_FLAGS 位 6 打开时只处理音效声道。
; 副作用：改写各声道状态与 APU 寄存器影子、SOUND_TEMPO_ACC、SOUND_CURRENT_CHANNEL、WINDOW_SAVE_0，并切换 $8000 窗口的页。
; 调用者：NMI_SOUND_UPDATE
SOUND_TICK:
    LDA SOUND_PLAYING
    BEQ SOUND_UPDATE_RETURN
    LDX #$07
@fx_loop:
    STX SOUND_CURRENT_CHANNEL
    LDA SOUND_CHANNEL_FLAGS,X
    BEQ @fx_update
    LDA SOUND_FX_PAGE
    JSR MAP_WINDOWS_8000
    JSR SOUND_FX_COUNTDOWN
@fx_update:
    LDA SOUND_UPDATE_FLAGS,X
    BEQ @fx_next
    JSR SOUND_FLUSH_CHANNEL
@fx_next:
    DEX
    CPX #$03
    BNE @fx_loop
    BIT SOUND_FLAGS
    BVS SOUND_UPDATE_RETURN
@music_loop:
    STX SOUND_CURRENT_CHANNEL
    JSR SOUND_VIBRATO_TICK
    JSR SOUND_FLUSH_CHANNEL
    JSR SOUND_ENVELOPE_TICK
    LDX SOUND_CURRENT_CHANNEL
    DEX
    BPL @music_loop
    LDA SOUND_TEMPO
    CLC
    ADC SOUND_TEMPO_ACC
    STA SOUND_TEMPO_ACC
    BCC SOUND_UPDATE_RETURN
    LDX #$03
@beat_loop:
    LDA SOUND_CHANNEL_FLAGS,X
    BEQ @beat_next
    STX SOUND_CURRENT_CHANNEL
    LDA SOUND_MUSIC_PAGE
    STA WINDOW_SAVE_0
    JSR MAP_WINDOWS_8000
    JSR SOUND_MUSIC_COUNTDOWN
@beat_next:
    DEX
    BPL @beat_loop
; 作用：声音每帧更新（NMI_SOUND_UPDATE 与 SOUND_TICK）的返回（RTS）。
; 调用者：NMI_SOUND_UPDATE、SOUND_TICK
SOUND_UPDATE_RETURN:
    RTS
; 作用：音效声道的 SOUND_DURATION_LEFT 减 1，减到 0 时取下一事件（转 SOUND_TRACK_RUN）。
; 输入：X=声道号（4-7）。
; 调用者：SOUND_TICK
SOUND_FX_COUNTDOWN:
    DEC SOUND_DURATION_LEFT,X
    BEQ SOUND_TRACK_RUN
    RTS
; 作用：音乐声道在拍到时的时长与释放计时处理：SOUND_RELEASE_BEATS_LEFT 为 1 时，SOUND_RELEASE_LEFT 减到 0 就置 SOUND_UPDATE_FLAGS 位 7，再让 SOUND_DURATION_LEFT 减 1，减到 0 时取下一事件；释放拍数不为 1 时，SOUND_DURATION_LEFT 减到 0 就重装为 SOUND_NOTE_LENGTH 并让释放拍数减 1。取下一事件前清本声道在 SOUND_FINISHED_MASK 里的位，SOUND_RELEASE_BEATS_LEFT 重装为 SOUND_RELEASE_BEATS，清 SOUND_CHANNEL_FLAGS 位 2，然后落入 SOUND_TRACK_RUN。
; 输入：X=声道号（3-0），SOUND_CURRENT_CHANNEL=同一声道号。
; 调用者：SOUND_TICK
SOUND_MUSIC_COUNTDOWN:
    LDA SOUND_RELEASE_BEATS_LEFT,X
    CMP #$01
    BNE @beat_step
    DEC SOUND_RELEASE_LEFT,X
    BNE @duration
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$80
    STA SOUND_UPDATE_FLAGS,X
@duration:
    DEC SOUND_DURATION_LEFT,X
    BEQ @next_event
    RTS
@beat_step:
    DEC SOUND_DURATION_LEFT,X
    BNE @return
    LDA SOUND_NOTE_LENGTH,X
    STA SOUND_DURATION_LEFT,X
    DEC SOUND_RELEASE_BEATS_LEFT,X
@return:
    RTS
@next_event:
    CPX #$03
    BCS @clear_finished_bit
@clear_finished_bit:
    LDA #$FE
    SEC
    LDX SOUND_CURRENT_CHANNEL
    BEQ @mask_ready
@rotate_mask:
    ROL A
    DEX
    BNE @rotate_mask
@mask_ready:
    AND SOUND_FINISHED_MASK
    STA SOUND_FINISHED_MASK
    CLC
    LDX SOUND_CURRENT_CHANNEL
    LDA SOUND_RELEASE_BEATS
    STA SOUND_RELEASE_BEATS_LEFT,X
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$FB
    STA SOUND_CHANNEL_FLAGS,X
; 作用：取出声道的音轨指针（SOUND_TRACK_POS_LO/HI），不小于循环终点（SOUND_LOOP_END_LO/HI）时回到循环点（SOUND_LOOP_POINT_LO/HI）并把循环终点设成 $FFFF；然后逐个事件执行（SOUND_TRACK_STEP）直到 C=1（遇到时长或命令要求等待），再保存指针。
; 输入：X=声道号。
; 输出：SOUND_TRACK_POS_LO/HI 指向下一个事件。
; 调用者：SOUND_FX_COUNTDOWN、SOUND_MUSIC_COUNTDOWN（顺序执行到这里）
SOUND_TRACK_RUN:
    LDA SOUND_TRACK_POS_LO,X
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_TRACK_POS_HI,X
    STA SOUND_TRACK_PTR_HI
    LDA SOUND_TRACK_PTR_HI
    CMP SOUND_LOOP_END_HI,X
    BCC @run
    LDA SOUND_TRACK_PTR_LO
    CMP SOUND_LOOP_END_LO,X
    BCC @run
    LDA SOUND_LOOP_POINT_LO,X
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_LOOP_POINT_HI,X
    STA SOUND_TRACK_PTR_HI
    LDA #$FF
    STA SOUND_LOOP_END_LO,X
    STA SOUND_LOOP_END_HI,X
@run:
    LDY #$00
@next_byte:
    JSR SOUND_TRACK_STEP
    BCC @next_byte
    JSR SOUND_ADVANCE_PTR
    LDA SOUND_TRACK_PTR_LO
    STA SOUND_TRACK_POS_LO,X
    LDA SOUND_TRACK_PTR_HI
    STA SOUND_TRACK_POS_HI,X
    RTS
; 作用：执行音轨的一个事件：SOUND_CHANNEL_FLAGS 位 1 打开时，同一事件重复 SOUND_REPEAT_COUNT 次（每次恢复 Y），减到 0 时清位 1 并让 Y 前进；位 1 为 0 时直接进入 SOUND_TRACK_BYTE。
; 输入：X=声道号，Y=事件在音轨里的偏移。
; 输出：C 同 SOUND_TRACK_BYTE，C=1 表示本声道要等待一段时长。
; 调用者：SOUND_TRACK_RUN
SOUND_TRACK_STEP:
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$02
    BEQ SOUND_TRACK_BYTE
    TYA
    PHA
    JSR SOUND_TRACK_BYTE
    DEC SOUND_REPEAT_COUNT,X
    BEQ @repeat_done
    PLA
    TAY
    RTS
@repeat_done:
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$FD
    STA SOUND_CHANNEL_FLAGS,X
    PLA
    RTS
; 作用：读音轨的一个事件：$00-$3F 是时长，$40-$BF 是音符（声道 4-7 转 SOUND_NOTE_FX，声道 0-3 转 SOUND_NOTE_MUSIC），$C0 以上是命令（转 SOUND_TRACK_COMMAND）。
; 输入：X=声道号，Y=事件在音轨里的偏移，音轨指针 SOUND_TRACK_PTR_LO/HI。
; 输出：C=1 表示本声道要等待一段时长；Y 指向下一个事件。
; 调用者：SOUND_TRACK_STEP
SOUND_TRACK_BYTE:
    LDA (SOUND_TRACK_PTR_LO),Y
    CMP #$40
    BCC @duration
    CMP #$C0
    BCC @note
    JMP SOUND_TRACK_COMMAND
@note:
    CPX #$04
    BCS SOUND_NOTE_FX
    BCC SOUND_NOTE_MUSIC
@duration:
    CPX #$04
    BCS SOUND_STORE_FX_DURATION
    BCC @store_music_duration
@store_music_duration:
    STA SOUND_NOTE_LENGTH,X
; 作用：时长参数乘以 SOUND_LENGTH_FACTOR 后取高字节（最小为 1）存入 SOUND_NOTE_LENGTH_SCALED，Y 前进 1，C=0 返回。
; 输入：A=时长，X=声道号。
; 调用者：SOUND_CMD_C7、SOUND_TRACK_BYTE（顺序执行到这里）
SOUND_STORE_SCALED_DURATION:
    STA SOUND_TEMP0
    LDA SOUND_LENGTH_FACTOR,X
    STA SOUND_TEMP1
    JSR MUL8_HIGH
    LDA SOUND_TEMP0
    BNE @store
    LDA #$01
@store:
    STA SOUND_NOTE_LENGTH_SCALED,X
    INY
    CLC
    RTS
; 作用：把时长存入 SOUND_DURATION_LEFT，Y 前进 1，C=1 返回（本声道等待这段时长）。
; 输入：A=时长，X=声道号（4-7）。
; 调用者：SOUND_TRACK_BYTE
SOUND_STORE_FX_DURATION:
    STA SOUND_DURATION_LEFT,X
    INY
    SEC
    RTS
; 作用：音效声道的音符：把音符值存入 SOUND_NOTE，置 SOUND_UPDATE_FLAGS 位 5（音高），Y 前进 1，C=0 返回。
; 输入：A=音符值，X=声道号。
; 调用者：SOUND_TRACK_BYTE、SOUND_CMD_C0、SOUND_CMD_C1
SOUND_NOTE_FX:
    STA SOUND_NOTE,X
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$20
    STA SOUND_UPDATE_FLAGS,X
    INY
    CLC
    RTS
; 作用：音乐声道的音符：音符值（低 6 位）加 SOUND_TRANSPOSE（声道 0-2 再加 SOUND_TRANSPOSE_GLOBAL）后存入 SOUND_NOTE；SOUND_RELEASE_LEFT 取 SOUND_NOTE_LENGTH_SCALED（SOUND_CHANNEL_FLAGS 位 3 打开时取 $FF），SOUND_DURATION_LEFT 取 SOUND_NOTE_LENGTH。音符值位 7 为 1 时后面带一个附加字节：位 6 把释放时长限制为不超过 SOUND_GATE_PARAM，位 7 把释放时长置 $FF（连音，SOUND_SLIDE_FLAG 为 0 时重新开始包络），位 5 置 SOUND_CHANNEL_FLAGS 位 2。声道 0-2 在 SOUND_SLIDE_FLAG 为 0 时重新开始包络，SOUND_CHANNEL_FLAGS 位 7 为 0 时重置颤音，最后清 SOUND_SLIDE_FLAG。置 SOUND_UPDATE_FLAGS 位 4、5，Y 前进，C=1 返回（等待这段时长）。
; 输入：A=音符字节（$40-$BF），X=声道号，C=0。
; 调用者：SOUND_TRACK_BYTE
SOUND_NOTE_MUSIC:
    PHA
    ADC SOUND_TRANSPOSE,X
    AND #$3F
    STA SOUND_NOTE,X
    CPX #$03
    BCS @release_type
    CLC
    ADC SOUND_TRANSPOSE_GLOBAL
    STA SOUND_NOTE,X
@release_type:
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$08
    BEQ @release_scaled
    LDA #$FF
    BNE @store_release
@release_scaled:
    LDA SOUND_NOTE_LENGTH_SCALED,X
@store_release:
    STA SOUND_RELEASE_LEFT,X
    LDA SOUND_NOTE_LENGTH,X
    STA SOUND_DURATION_LEFT,X
    PLA
    BPL @restart_envelope
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_TEMP0
    LDA #$40
    BIT SOUND_TEMP0
    BEQ @tie_flag
    LDA SOUND_NOTE_LENGTH,X
    CMP SOUND_GATE_PARAM,X
    BCC @store_gate
    LDA SOUND_GATE_PARAM,X
@store_gate:
    STA SOUND_RELEASE_LEFT,X
@tie_flag:
    LDA #$80
    BIT SOUND_TEMP0
    BEQ @bit5_flag
    LDA #$FF
    STA SOUND_RELEASE_LEFT,X
    LDA SOUND_SLIDE_FLAG,X
    BNE @bit5_flag
    LDA #$00
    STA SOUND_ENVELOPE_COUNT,X
@bit5_flag:
    LDA #$20
    BIT SOUND_TEMP0
    BEQ @vibrato_check
    LDA SOUND_CHANNEL_FLAGS,X
    ORA #$04
    STA SOUND_CHANNEL_FLAGS,X
@restart_envelope:
    CPX #$03
    BCS @vibrato_check
    LDA SOUND_SLIDE_FLAG,X
    BNE @clear_slide
    LDA #$00
    STA SOUND_ENVELOPE_COUNT,X
@vibrato_check:
    CPX #$03
    BCS @finish
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$80
    BNE @finish
    JSR SOUND_VIBRATO_RESET
@clear_slide:
    LDA #$00
    STA SOUND_SLIDE_FLAG,X
@finish:
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$30
    STA SOUND_UPDATE_FLAGS,X
    INY
    SEC
    RTS
; 作用：执行音轨命令 $C0-$E5：按 SOUND_COMMAND_TABLE 间接跳转。
; 输入：A=命令字节，Y=命令字节在音轨里的偏移。
; 输出：进入命令时 X=SOUND_CURRENT_CHANNEL，Y 指向第一个参数，C=0；命令返回时 C=1 表示本声道等待一段时长，Y 指向下一个事件。
; 调用者：SOUND_TRACK_BYTE
SOUND_TRACK_COMMAND:
    AND #$3F
    ASL A
    TAX
    LDA SOUND_COMMAND_TABLE,X
    STA SOUND_TEMP0
    LDA SOUND_COMMAND_TABLE+1,X
    STA SOUND_TEMP1
    LDX SOUND_CURRENT_CHANNEL
    INY
    CLC
    JMP (SOUND_TEMP0)
; 作用：音轨命令入口表：38 项×2 字节，命令字节减 $C0 为序号。
; 引用者：SOUND_TRACK_COMMAND
SOUND_COMMAND_TABLE:
    .word SOUND_CMD_C0,SOUND_CMD_C1,SOUND_CMD_C2,SOUND_CMD_C3,SOUND_CMD_C4,SOUND_CMD_C5,SOUND_CMD_C6,SOUND_CMD_C7,SOUND_CMD_C8,SOUND_CMD_C9
    .word SOUND_CMD_CA,SOUND_CMD_CB,SOUND_CMD_CC,SOUND_CMD_CD,SOUND_CMD_CE,SOUND_CMD_CF,SOUND_CMD_STOP_SONG,SOUND_CMD_D1
    .word SOUND_CMD_D2,SOUND_CMD_STOP_CHANNEL,SOUND_CMD_D4,SOUND_CMD_D5,SOUND_CMD_D6,SOUND_CMD_D7,SOUND_CMD_D8,SOUND_CMD_D9
    .word SOUND_CMD_DA,SOUND_CMD_DB,SOUND_CMD_DC,SOUND_CMD_DD,SOUND_CMD_DE,SOUND_CMD_DF,SOUND_CMD_FX_REG1,SOUND_CMD_FX_REG2
    .word SOUND_CMD_FX_REG3,SOUND_CMD_FX_REG0,SOUND_CMD_FX_TRIGGER,SOUND_CMD_E5
; 作用：音轨命令 $C0（1 个参数）：把参数当作音符，转 SOUND_NOTE_FX。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C0:
    LDA (SOUND_TRACK_PTR_LO),Y
    JMP SOUND_NOTE_FX
; 作用：音轨命令 $C1（1 个参数）：参数加到 SOUND_NOTE 的音符上，转 SOUND_NOTE_FX。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C1:
    LDA (SOUND_TRACK_PTR_LO),Y
    ADC SOUND_NOTE,X
    JMP SOUND_NOTE_FX
; 作用：音轨命令 $C2（1 个参数）：写 SOUND_PITCH_OFFSET（转 SOUND_STORE_PITCH_OFFSET）。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C2:
    LDA (SOUND_TRACK_PTR_LO),Y
    BCC SOUND_STORE_PITCH_OFFSET
; 作用：音轨命令 $C3（1 个参数）：加到 SOUND_PITCH_OFFSET，参数为正时进位使 SOUND_NOTE 加 1，参数为负时借位使 SOUND_NOTE 减 1（转 SOUND_STORE_PITCH_OFFSET）。
; 调用者：SOUND_COMMAND_TABLE（地址表）、SOUND_CMD_C2（顺序执行到这里）
SOUND_CMD_C3:
    LDA (SOUND_TRACK_PTR_LO),Y
    BMI @negative
    ADC SOUND_PITCH_OFFSET,X
    BCC SOUND_STORE_PITCH_OFFSET
    INC SOUND_NOTE,X
    BCS SOUND_STORE_PITCH_OFFSET
@negative:
    ADC SOUND_PITCH_OFFSET,X
    BCS SOUND_STORE_PITCH_OFFSET
    DEC SOUND_NOTE,X
; 作用：命令 $C2、$C3 共用：A 存入 SOUND_PITCH_OFFSET，置 SOUND_UPDATE_FLAGS 位 5（音高），Y 前进 1，C=0 返回。
; 调用者：SOUND_CMD_C2、SOUND_CMD_C3
SOUND_STORE_PITCH_OFFSET:
    STA SOUND_PITCH_OFFSET,X
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$20
    STA SOUND_UPDATE_FLAGS,X
    INY
    CLC
    RTS
; 作用：音轨命令 $C4（1 个参数）：写 SOUND_VOLUME（转 SOUND_STORE_VOLUME）。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C4:
    LDA (SOUND_TRACK_PTR_LO),Y
    BCC SOUND_STORE_VOLUME
; 作用：音轨命令 $C5（1 个参数）：加到 SOUND_VOLUME。
; 调用者：SOUND_COMMAND_TABLE（地址表）、SOUND_CMD_C4（顺序执行到这里）
SOUND_CMD_C5:
    LDA (SOUND_TRACK_PTR_LO),Y
    ADC SOUND_VOLUME,X
; 作用：命令 $C4、$C5 共用：A 存入 SOUND_VOLUME，置 SOUND_UPDATE_FLAGS 位 3（音量），Y 前进 1，C=0 返回。
; 调用者：SOUND_CMD_C4、SOUND_CMD_C5（顺序执行到这里）
SOUND_STORE_VOLUME:
    STA SOUND_VOLUME,X
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$08
    STA SOUND_UPDATE_FLAGS,X
    INY
    CLC
    RTS
; 作用：音轨命令 $C6（1 个参数）：写 SOUND_ENVELOPE_RATE（包络速度），Y 前进 1。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C6:
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_ENVELOPE_RATE,X
    INY
    RTS
; 作用：音轨命令 $C7（1 个参数）：写 SOUND_LENGTH_FACTOR，并按当前 SOUND_NOTE_LENGTH 重算 SOUND_NOTE_LENGTH_SCALED（转 SOUND_STORE_SCALED_DURATION）。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C7:
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_LENGTH_FACTOR,X
    LDA SOUND_NOTE_LENGTH,X
    JMP SOUND_STORE_SCALED_DURATION
; 作用：音轨命令 $C8（1 个参数）：写 SOUND_GATE_PARAM（音符占空参数），Y 前进 1。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C8:
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_GATE_PARAM,X
    INY
    RTS
; 作用：音轨命令 $C9（0 个参数）：休止：SOUND_DURATION_LEFT 取 SOUND_NOTE_LENGTH，置本声道在 SOUND_FINISHED_MASK 里的位，再按命令 $CB 处理（置 SOUND_UPDATE_FLAGS 位 7），C=1 返回。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_C9:
    LDA SOUND_NOTE_LENGTH,X
    STA SOUND_DURATION_LEFT,X
    LDA #$01
    LDX SOUND_CURRENT_CHANNEL
    BEQ @mask_ready
@rotate_mask:
    ASL A
    DEX
    BNE @rotate_mask
@mask_ready:
    ORA SOUND_FINISHED_MASK
    STA SOUND_FINISHED_MASK
    LDX SOUND_CURRENT_CHANNEL
    SEC
    BCS SOUND_CMD_CB
; 作用：音轨命令 $CA（0 个参数）：置 SOUND_UPDATE_FLAGS 位 4（发声）。
; 调用者：SOUND_COMMAND_TABLE（地址表）、SOUND_CMD_C9（顺序执行到这里）
SOUND_CMD_CA:
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$10
    STA SOUND_UPDATE_FLAGS,X
    RTS
; 作用：音轨命令 $CB（0 个参数）：置 SOUND_UPDATE_FLAGS 位 7（静音）。
; 调用者：SOUND_COMMAND_TABLE（地址表）、SOUND_CMD_C9
SOUND_CMD_CB:
    LDA SOUND_UPDATE_FLAGS,X
    ORA #$80
    STA SOUND_UPDATE_FLAGS,X
    RTS
; 作用：音轨命令 $CC（1 个参数）：写拍速 SOUND_TEMPO、SOUND_TEMPO_HI，Y 前进 1。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_CC:
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_TEMPO
    STA SOUND_TEMPO_HI
    INY
    RTS
; 作用：音轨命令 $CD（2 个参数）：设音色。
; 声道 3（噪声）：只用第 1 个参数的低 6 位在 SOUND_INSTRUMENT_TABLE 里选噪声音色指针（SOUND_NOISE_PTR_LO/HI），SOUND_NOISE_REG0 置位 $30，之后 X 被改成（参数 & $3F）× 2，后面的音轨字节按这个“声道”解释（用例 cd-noise-*）；声道 2、6 只跳过 2 个参数。
; 其余声道：按第 1 个参数（位 7 为 1 时换入第二页 SOUND_MUSIC_PAGE2，取零页 SOUND_TEMP4 指向的指针表；位 6 为 1 时取 SOUND_INSTRUMENT_TABLE；否则取 SOUND_PATTERN_TABLE）与第 2 个参数（项号）选一个 4 字节的音色项：包络指针 2 字节（声道 0-3 存入 SOUND_ENVELOPE_PTR_LO/HI）、寄存器 0 的值（置位 $30）、寄存器 1 的值；寄存器值写入本声道的 SOUND_REG_SHADOW，并置 SOUND_UPDATE_FLAGS 位 6；声道 0-3 的第 1 个参数还存入 SOUND_INSTRUMENT_FLAGS。
; 输出：Y 跳过 2 个参数，C=0。
; 调用者：SOUND_COMMAND_TABLE（地址表）
SOUND_CMD_CD:
    CPX #$03
    BEQ @noise
    TXA
    AND #$03
    CMP #$02
    BNE @select_table
    INY
    INY
    CLC
    RTS
