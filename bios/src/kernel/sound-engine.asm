; 作用：按 SOUND_UPDATE_FLAGS 各位把声道待更新的项写到寄存器：位 7 静音、位 6 寄存器 0-1、位 5 音高、位 3 音量、位 2 寄存器 1、位 4 发声、位 1 音效寄存器 2-3、位 0 滑音；处理完把 SOUND_UPDATE_FLAGS 清 0。
; 输入：X=声道号。
; 调用者：SOUND_TICK
SOUND_FLUSH_CHANNEL:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$80
    BEQ @check_reg01
    JSR SOUND_APPLY_KEY_OFF
@check_reg01:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$40
    BEQ @check_pitch
    JSR SOUND_APPLY_REG01
@check_pitch:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$20
    BEQ @check_level
    JSR SOUND_APPLY_PITCH
@check_level:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$08
    BEQ @check_reg1
    JSR SOUND_APPLY_LEVEL
@check_reg1:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$04
    BEQ @check_note_on
    JSR SOUND_APPLY_REG1
@check_note_on:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$10
    BEQ @check_fx_reg23
    JSR SOUND_APPLY_NOTE_ON
@check_fx_reg23:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$02
    BEQ @check_bend
    JSR SOUND_APPLY_FX_REG23
@check_bend:
    LDA SOUND_UPDATE_FLAGS,X
    AND #$01
    BEQ @clear_flags
    JSR SOUND_APPLY_PITCH_BEND
@clear_flags:
    LDA #$00
    STA SOUND_UPDATE_FLAGS,X
    RTS
; 作用：声道 0-3 每帧的包络推进：声道 0、1 与声道 3（噪声，状态存在索引 2 的槽位里）求出音量；声道 2（三角波）没有包络；SOUND_ENVELOPE_STAGE 为 0（包络已结束）时直接返回。SOUND_INSTRUMENT_FLAGS 位 7 为 1 时先换入第二页 SOUND_MUSIC_PAGE2（处理完换回音乐页），位 6 为 1 用 SOUND_ENVELOPE_RUN，否则用 SOUND_VOLUME_ENVELOPE。
; 输入：X=SOUND_CURRENT_CHANNEL（0-3）。
; 调用者：SOUND_TICK
SOUND_ENVELOPE_TICK:
    CPX #$02
    BCC @tone_channel
    CPX #$03
    BEQ @noise_channel
    RTS
@noise_channel:
    DEX
@tone_channel:
    LDA SOUND_ENVELOPE_STAGE,X
    BNE @active
    RTS
@active:
    LDX SOUND_CURRENT_CHANNEL
    CPX #$03
    BNE @tone_flags
    DEX
    BNE @run_envelope
    RTS
@tone_flags:
    LDA SOUND_INSTRUMENT_FLAGS,X
    BMI @paged
    AND #$40
    BEQ @volume_envelope
@run_envelope:
    LDA SOUND_ENVELOPE_STAGE,X
    JSR SOUND_ENVELOPE_RUN
    RTS
@volume_envelope:
    JMP SOUND_VOLUME_ENVELOPE
@paged:
    LDA SOUND_MUSIC_PAGE
    PHA
    LDA SOUND_MUSIC_PAGE2
    JSR MAP_WINDOWS_8000
    LDA SOUND_INSTRUMENT_FLAGS,X
    AND #$40
    BEQ @paged_volume_envelope
    LDA SOUND_ENVELOPE_STAGE,X
    JSR SOUND_ENVELOPE_RUN
    PLA
    STA SOUND_MUSIC_PAGE
    JSR MAP_WINDOWS_8000
    RTS
@paged_volume_envelope:
    JSR SOUND_VOLUME_ENVELOPE
    PLA
    STA SOUND_MUSIC_PAGE
    JSR MAP_WINDOWS_8000
    RTS
; 作用：按包络表（SOUND_ENVELOPE_PTR_LO/HI 指向）分段推进一步（攻击、保持、衰减等），求出 SOUND_ENVELOPE_LEVEL，再按 SOUND_VOLUME 缩放（MUL8_HIGH）后写入寄存器 0 的低 4 位（SOUND_WRITE_REG）。
; 输入：A=SOUND_ENVELOPE_STAGE（当前段在包络表里的偏移，位 7 为 1 表示渐变段），X=包络槽位。
; 输出：SOUND_ENVELOPE_LEVEL、SOUND_ENVELOPE_STAGE、SOUND_ENVELOPE_COUNT 更新，APU 寄存器 0 的音量改变。
; 调用者：SOUND_ENVELOPE_TICK
SOUND_ENVELOPE_RUN:
    TAY
    LDA SOUND_ENVELOPE_PTR_LO,X
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_ENVELOPE_PTR_HI,X
    STA SOUND_TRACK_PTR_HI
    TYA
    BMI @ramp
    CMP #$02
    BEQ @stage2
    CMP #$01
    BEQ @stage1
    LDA (SOUND_TRACK_PTR_LO),Y
    CLC
    ADC SOUND_ENVELOPE_LEVEL,X
    STA SOUND_ENVELOPE_LEVEL,X
    DEC SOUND_ENVELOPE_COUNT,X
    BNE @write_level
    INY
    INY
    BNE @next_segment
@stage2:
    DEY
    LDA (SOUND_TRACK_PTR_LO),Y
    CMP SOUND_ENVELOPE_LEVEL,X
    BCS @stage2_done
    STA SOUND_ENVELOPE_LEVEL,X
@stage2_done:
    INY
    TYA
    ORA #$80
    STA SOUND_ENVELOPE_STAGE,X
    BNE @write_level
@stage1:
    DEY
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_ENVELOPE_LEVEL,X
    LDY #$03
    BNE @next_segment
@ramp:
    AND #$7F
    TAY
    LDA (SOUND_TRACK_PTR_LO),Y
    BMI @ramp_negative
    CLC
    ADC SOUND_ENVELOPE_LEVEL,X
    BCC @ramp_store_level
    LDA #$FF
    BCS @ramp_store_clamped
@ramp_negative:
    ADC SOUND_ENVELOPE_LEVEL,X
    BCS @ramp_store_level
    LDA #$00
@ramp_store_clamped:
    STA SOUND_ENVELOPE_LEVEL,X
    LDA #$00
    STA SOUND_ENVELOPE_STAGE,X
    BEQ @write_level
@ramp_store_level:
    STA SOUND_ENVELOPE_LEVEL,X
    BCS @write_level
@next_segment:
    TYA
    STA SOUND_ENVELOPE_STAGE,X
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_ENVELOPE_COUNT,X
    BNE @write_level
    DEY
    LDA (SOUND_TRACK_PTR_LO),Y
    BNE @mark_ramp
    STA SOUND_ENVELOPE_STAGE,X
    BEQ @write_level
@mark_ramp:
    LDA SOUND_ENVELOPE_STAGE,X
    ORA #$80
    STA SOUND_ENVELOPE_STAGE,X
@write_level:
    STX SOUND_TRACK_PTR_LO
    LDX SOUND_CURRENT_CHANNEL
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$04
    BEQ @add_volume
    LDA SOUND_ENVELOPE_RATE,X
@add_volume:
    SEC
    ADC SOUND_VOLUME,X
    STA SOUND_TEMP1
    LDX SOUND_TRACK_PTR_LO
    LDA SOUND_ENVELOPE_LEVEL,X
    STA SOUND_TEMP0
    JSR MUL8_HIGH
    LSR SOUND_TEMP0
    LSR SOUND_TEMP0
    LSR SOUND_TEMP0
    LDA SOUND_CURRENT_CHANNEL
    TAX
    ASL A
    ASL A
    TAY
    LDA SOUND_REG_SHADOW,Y
    AND #$F0
    ORA SOUND_TEMP0
    JMP SOUND_WRITE_REG
; 作用：另一种包络：把计数 SOUND_ENVELOPE_COUNT 占 SOUND_VOLUME 的比例换成 0-15 的序号，在包络表（SOUND_ENVELOPE_PTR_LO/HI 指向）里取值，与起始音量（SOUND_ENVELOPE_LEVEL）合成后经 SOUND_VOLUME_SCALE 换算，写入寄存器 0 的低 4 位；之后计数加 1（不超过 SOUND_VOLUME）。
; 输入：X=包络槽位，SOUND_CURRENT_CHANNEL=声道号。
; 调用者：SOUND_ENVELOPE_TICK
SOUND_VOLUME_ENVELOPE:
    CPX #$02
    BCS @use_volume
    TXA
    CLC
    ADC #$01
    AND SOUND_FINISHED_MASK
    BEQ @use_volume
    LDA #$00
    BEQ @store_level
@use_volume:
    LDA SOUND_VOLUME,X
    AND #$0F
@store_level:
    STA SOUND_ENVELOPE_LEVEL,X
    LDA SOUND_ENVELOPE_PTR_LO,X
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_ENVELOPE_PTR_HI,X
    STA SOUND_TRACK_PTR_HI
    LDA #$00
    STA SOUND_ENVELOPE_TEMP
    LDA SOUND_ENVELOPE_COUNT,X
    PHA
    LDY #$03
@divide_bit:
    ASL A
    BCC @compare
    SBC SOUND_VOLUME,X
    SEC
    BCS @quotient_bit
@compare:
    CMP SOUND_VOLUME,X
    BCC @quotient_bit
    SBC SOUND_VOLUME,X
@quotient_bit:
    ROL SOUND_ENVELOPE_TEMP
    DEY
    BPL @divide_bit
    PLA
    STA SOUND_ENVELOPE_COUNT,X
    INC SOUND_ENVELOPE_COUNT,X
    LDA SOUND_ENVELOPE_COUNT,X
    CMP SOUND_VOLUME,X
    BCC @lookup
    LDA SOUND_VOLUME,X
    STA SOUND_ENVELOPE_COUNT,X
@lookup:
    LDY SOUND_ENVELOPE_TEMP
    LDA (SOUND_TRACK_PTR_LO),Y
    ORA SOUND_ENVELOPE_LEVEL,X
    TAY
    LDA SOUND_VOLUME_SCALE,Y
    STA SOUND_TEMP0
    LDA SOUND_CURRENT_CHANNEL
    TAX
    ASL A
    ASL A
    TAY
    LDA SOUND_REG_SHADOW,Y
    AND #$F0
    ORA SOUND_TEMP0
    JMP SOUND_WRITE_REG
; 作用：声道静音（SOUND_UPDATE_FLAGS 位 7）：清 SOUND_CHANNEL_FLAGS 位 7；三角波（声道 2、6）走 SOUND_KEY_OFF_TRIANGLE，音效声道走 SOUND_KEY_OFF_CLEAR_VOLUME，音乐声道进入释放阶段（SOUND_SET_ENVELOPE_STAGE，A=2）。
; 输入：X=声道号。
; 调用者：SOUND_FLUSH_CHANNEL
SOUND_APPLY_KEY_OFF:
    LDA SOUND_CHANNEL_FLAGS,X
    AND #$7F
    STA SOUND_CHANNEL_FLAGS,X
    TXA
    AND #$03
    CMP #$02
    BEQ SOUND_KEY_OFF_TRIANGLE
    CPX #$04
    BCS SOUND_KEY_OFF_CLEAR_VOLUME
    LDA #$02
    JMP SOUND_SET_ENVELOPE_STAGE
; 作用：把 A 存入 SOUND_ENVELOPE_STAGE 的声道项（声道 3 用项 2）；A=2 表示释放阶段，A=1 表示新音符开始。
; 输入：A=阶段，X=声道号。
; 输出：X 不变。
; 调用者：SOUND_APPLY_KEY_OFF、SOUND_APPLY_NOTE_ON
SOUND_SET_ENVELOPE_STAGE:
    STX SOUND_TEMP0
    CPX #$03
    BNE @store
    DEX
@store:
    STA SOUND_ENVELOPE_STAGE,X
    LDX SOUND_TEMP0
    RTS
; 作用：音效声道静音：寄存器 0 影子的低 4 位清 0 后写出。
; 输入：X=声道号。
; 调用者：SOUND_APPLY_KEY_OFF
SOUND_KEY_OFF_CLEAR_VOLUME:
