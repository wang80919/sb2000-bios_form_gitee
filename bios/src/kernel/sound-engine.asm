    ASL A
    ASL A
    TAY
    INY
    INY
    LDA SOUND_REG_SHADOW,Y
    JSR SOUND_WRITE_REG
    INY
    LDA SOUND_REG_SHADOW,Y
    JMP SOUND_WRITE_REG
; 作用：音量（SOUND_UPDATE_FLAGS 位 3）：只有音效声道（4-7，三角波除外）在发声中（SOUND_CHANNEL_FLAGS 位 7 为 1）时才写出音量（SOUND_APPLY_LEVEL_WRITE）；音乐声道的音量由包络决定。
