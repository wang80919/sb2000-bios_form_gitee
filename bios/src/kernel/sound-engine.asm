    LDA #$01
    JMP SOUND_SET_ENVELOPE_STAGE
@triangle:
    JSR SOUND_WRITE_REG23
    TXA
    ASL A
    ASL A
    TAY
    LDA #$81
    JMP SOUND_WRITE_REG
; 作用：把寄存器影子的第 3、4 个字节（寄存器 2、3）写到 APU。
