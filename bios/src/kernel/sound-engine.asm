    BVC @pattern_table
    LDA SOUND_PATTERN_INDEX
    AND #$3F
    ASL A
    TAX
    LDA SOUND_INSTRUMENT_TABLE,X
    STA SOUND_TEMP0
    LDA SOUND_INSTRUMENT_TABLE+1,X
    STA SOUND_TEMP1
    JMP @add_offset
