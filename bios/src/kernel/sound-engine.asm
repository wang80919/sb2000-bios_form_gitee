    LDA SOUND_PATTERN_INDEX
    AND #$3F
    ASL A
    TAY
    LDA (SOUND_TEMP4),Y
    STA SOUND_TEMP0
    INY
    LDA (SOUND_TEMP4),Y
    STA SOUND_TEMP1
    LDA SOUND_PATTERN_OFFSET
    ASL A
    ASL A
    CLC
    ADC SOUND_TEMP0
    STA SOUND_TEMP0
    LDA SOUND_TEMP1
    ADC #$00
    STA SOUND_TEMP1
    JMP @read_entry
@bit6_check:
