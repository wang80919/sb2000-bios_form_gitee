; 功能 $74 子功能 1：$032B 位 6 置位
; 调用者：API74_JUMP_TABLE（地址表）
API74_SUB_1:
    LDA PORT4302_FLAGS
    ORA #$40
    STA PORT4302_FLAGS
    JMP WAIT_VBLANK_RETURN
; 作用：功能 $74 子功能 2：$032B 位 1 置位
; 调用者：API74_JUMP_TABLE（地址表）
API74_SUB_2:
    LDA PORT4302_FLAGS
    ORA #$02
    STA PORT4302_FLAGS
    JMP WAIT_VBLANK_RETURN
; 作用：功能 $74 子功能 3：$032B 位 1 清除
; 调用者：API74_JUMP_TABLE（地址表）
API74_SUB_3:
    LDA PORT4302_FLAGS
    AND #$FD
    STA PORT4302_FLAGS
    JMP WAIT_VBLANK_RETURN
; 作用：功能 $74 子功能 4：$032B 位 2 置位
; 调用者：API74_JUMP_TABLE（地址表）
API74_SUB_4:
