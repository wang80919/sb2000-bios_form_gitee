    LDA #$FF
    STA APU_STATUS
    PLA
    STA SYS_GROUP
    PLA
    STA PROG_ENTRY_HI
    PLA
    STA PROG_ENTRY_LO
    LDA #$EF
    STA TIMER_CTRL
    LDA #$3C
    STA TIMER_COUNT
    RTS
; 作用：子功能 13：$0652 为重复次数，每次先调用功能 $1B 再播放 WAV（SOUND_PLAY_WAV），播完把 APU 状态寄存器置 $FF
