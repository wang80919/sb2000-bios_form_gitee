    STA SYS_GROUP
    LDA PROG_ENTRY_LO
    STA SOUND_TRACK_PTR_LO
    LDA PROG_ENTRY_HI
    STA SOUND_TRACK_PTR_HI
    LDA #$00
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
    LDA #$FF
    STA SOUND_SONG_PARAM
    LDA SYS_GROUP
    STA SOUND_MUSIC_PAGE
    LDA WINDOW_SAVE_0
    PHA
    LDA SOUND_MUSIC_PAGE
    STA WINDOW_SAVE_0
    JSR MAP_WINDOWS_8000
    LDA #$7F
