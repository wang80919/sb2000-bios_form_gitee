; 作用：子功能 2：停止播放（曲号 $FC、$FD 两个控制命令），并把 $03A1 置 $FF；实测被 game/GAME.EXE、wps/SB-WIN.EXE 调用
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_02:
    LDA #$FC
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
    LDA #$FD
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
    LDA SOUND_FLAGS
    AND #$7F
    STA SOUND_FLAGS
    LDA #$02
    STA SYS_SUBFUNCTION
    JSR API_12_PPU_CONTROL
    LDA #$FF
    STA SOUND_STATUS
    RTS
; 作用：子功能 3：把 $03A1 取到 $0653，用作查询结果
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_03:
    LDA SOUND_STATUS
    STA SYS_ARG_10
    RTS
; 作用：子功能 4：把 $0653 加到 4 个声道的 $0447-$044A
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_04:
    LDA SOUND_FLAGS
    AND #$7F
    STA SOUND_FLAGS
    LDX #$03
@loop:
    LDA SOUND_TRANSPOSE,X
    CLC
    ADC SYS_ARG_10
    STA SOUND_TRANSPOSE,X
    DEX
    BPL @loop
    LDA SOUND_FLAGS
    ORA #$80
    STA SOUND_FLAGS
    RTS
; 作用：子功能 5：把 $0653 加到 $03D4，并同步写 $03D5
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_05:
    LDA SOUND_FLAGS
    AND #$7F
    STA SOUND_FLAGS
    LDA SOUND_TEMPO
    CLC
    ADC SYS_ARG_10
    STA SOUND_TEMPO
    STA SOUND_TEMPO_HI
    LDA SOUND_FLAGS
    ORA #$80
    STA SOUND_FLAGS
    RTS
; 作用：子功能 6：$03A4 置 0，再执行 SOUND_ADJUST_X；X 是分发时留下的子功能号乘 2，所以实际加到 $040B，与声道号无关（用例 p04-sound-ctl.mjs）
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_06:
    LDA #$00
    BEQ SOUND_ADJUST_X
; 作用：子功能 7：$03A4 置 1，再执行 SOUND_ADJUST_X
; 调用者：SOUND_SUB_TABLE（地址表）、SOUND_SUB_06（顺序执行到这里）
SOUND_SUB_07:
    LDA #$01
    BNE SOUND_ADJUST_X
; 作用：子功能 8：$03A4 置 3，再执行 SOUND_ADJUST_X
; 调用者：SOUND_SUB_TABLE（地址表）、SOUND_SUB_07（顺序执行到这里）
SOUND_SUB_08:
    LDA #$03
; 作用：子功能 6-8 的共用部分：写 $03A4，暂停发声更新（$0499 清最高位），$03FF+X 加上 $0653，再恢复
; 调用者：SOUND_SUB_06、SOUND_SUB_07、SOUND_SUB_08（顺序执行到这里）
SOUND_ADJUST_X:
    STA SOUND_ADJUST_TEMP
    LDA SOUND_FLAGS
    AND #$7F
    STA SOUND_FLAGS
    LDA SOUND_DUMMY_READ
    LDA SOUND_VOLUME,X
    CLC
    ADC SYS_ARG_10
    STA SOUND_VOLUME,X
    LDA SOUND_FLAGS
    ORA #$80
    STA SOUND_FLAGS
    RTS
; 作用：按 $049A 开始播放：0 为复位并停止，$FB-$FF 为控制命令，其余为曲号（曲表指针在 $D31B 起）；$03A6 非 0 时直接用 SOUND_TRACK_PTR_LO/SOUND_TRACK_PTR_HI 指向的数据
; 调用者：NMI_SOUND_UPDATE、SOUND_SUB_00、SOUND_SUB_01、SOUND_SUB_02、SOUND_SUB_09、SOUND_SUB_0A、SOUND_SUB_0B
SOUND_PLAY_SONG:
    LDA SOUND_FLAGS
    AND #$7F
    STA SOUND_FLAGS
    LDX SOUND_NEXT_SONG
    BEQ @reset
    BPL @start_song
    INX
    BEQ @resume
    INX
    BEQ @stop_apu
    INX
    BEQ @set_fx_flag
    INX
    BEQ @keep_prev_reset
    INX
    BEQ @mute_flag
@reset:
    JSR SOUND_RESET
    JMP SOUND_ENABLE_APU
@mute_flag:
    LDA SOUND_FLAGS
    AND #$DF
    STA SOUND_FLAGS
    JMP SOUND_SET_ACTIVE_FLAG
@keep_prev_reset:
    LDA SOUND_SONG_NUMBER_PREV
    PHA
    JSR SOUND_RESET
    PLA
    STA SOUND_SONG_NUMBER_PREV
    JMP SOUND_ENABLE_APU
@set_fx_flag:
    LDA SOUND_FLAGS
    ORA #$40
    STA SOUND_FLAGS
@stop_apu:
    LDA SOUND_SONG_NUMBER
    STA SOUND_SONG_NUMBER_PREV
    LDA #$00
    STA APU_STATUS
    JMP SOUND_SET_ACTIVE_FLAG
@resume:
    LDA SOUND_FLAGS
    AND #$BF
    STA SOUND_FLAGS
    LDA SOUND_SONG_NUMBER_PREV
    BEQ @stop_channels
    CMP SOUND_SONG_NUMBER
    BEQ @stop_channels
    TAX
    JMP @start_song
@stop_channels:
    LDX #$07
@loop:
    STX SOUND_CURRENT_CHANNEL
    JSR SOUND_CMD_STOP_CHANNEL
    LDX SOUND_CURRENT_CHANNEL
    DEX
    CPX #$03
    BNE @loop
    JMP SOUND_ENABLE_APU
@start_song:
    LDA SOUND_SONG_PARAM
    BNE SOUND_START_TRACKS
    DEX
    TXA
    ASL A
    TAX
    LDA SOUND_SONG_TABLE,X
    STA SOUND_TRACK_PTR_LO
    LDA SOUND_SONG_TABLE+1,X
    STA SOUND_TRACK_PTR_HI
; 作用：从 SOUND_TRACK_PTR_LO/SOUND_TRACK_PTR_HI 指向的曲数据取出各声道的起始地址并初始化声道状态
; 调用者：SOUND_CMD_D9、SOUND_PLAY_SONG、SOUND_SUB_0A、SOUND_SUB_0B
SOUND_START_TRACKS:
    LDY #$00
    LDA (SOUND_TRACK_PTR_LO),Y
    BMI @music_track
    STA SOUND_TEMP0
    LDA SOUND_TRACK_PTR_LO
    STA SOUND_FX_BASE_LO
    STA SOUND_MUSIC_BASE_SAVED_LO
    LDA SOUND_TRACK_PTR_HI
    STA SOUND_FX_BASE_HI
    STA SOUND_MUSIC_BASE_SAVED_HI
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    BPL @check_priority
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    STA SOUND_AUTO_COUNT
    LDA SOUND_NEXT_SONG
    STA SOUND_AUTO_RELOAD
    LDA SOUND_FLAGS
    ORA #$20
    STA SOUND_FLAGS
@loop:
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    BMI SOUND_INIT_TRACKS
@check_priority:
    TAX
    LDA SOUND_TEMP0
    CMP SOUND_SONG_NUMBER,X
    BCC @done_inactive
    INY
    INY
    BNE @loop
@done_inactive:
    JMP SOUND_SET_ACTIVE_FLAG
@music_track:
    LDA SOUND_NEXT_SONG
    CMP SOUND_SONG_NUMBER
    BNE @new_music
    JMP SOUND_ENABLE_APU
@new_music:
    STA SOUND_SONG_NUMBER
    LDA #$FF
    STA SOUND_TEMPO_ACC
    STA SOUND_TEMPO
    STA SOUND_TEMPO_HI
    LDA SOUND_FLAGS
    ORA #$02
    AND #$BF
    STA SOUND_FLAGS
    LDA SOUND_TRACK_PTR_LO
    STA SOUND_MUSIC_BASE_LO
    STA SOUND_MUSIC_BASE_SAVED_LO
    LDA SOUND_TRACK_PTR_HI
    STA SOUND_MUSIC_BASE_HI
    STA SOUND_MUSIC_BASE_SAVED_HI
; 作用：按曲子头的声道项初始化每个声道的音轨指针与状态（$03D7/$03DF、$03C3、$03CB 等），再把 APU 状态置 $0F；SOUND_START_TRACKS 与命令 $D0 都会进入
; 调用者：SOUND_CMD_STOP_SONG、SOUND_START_TRACKS
SOUND_INIT_TRACKS:
    LDY #$01
    LDA (SOUND_TRACK_PTR_LO),Y
    BPL @loop
    INY
    INY
@loop:
    LDA (SOUND_TRACK_PTR_LO),Y
    BMI SOUND_ENABLE_APU
    TAX
    CPX #$04
    BCC @channel_init
    LDA SOUND_TEMP0
    STA SOUND_SONG_NUMBER,X
    BNE @set_position
@channel_init:
    CPX #$03
    BCS @channel_reset
    LDA #$1E
    STA SOUND_VIBRATO_STEP,X
    LDA #$96
    STA SOUND_VIBRATO_RATE,X
@channel_reset:
    LDA #$F0
    STA SOUND_LENGTH_FACTOR,X
    LDA #$00
    STA SOUND_TRANSPOSE,X
@set_position:
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    CLC
    ADC SOUND_MUSIC_BASE_SAVED_LO
    STA SOUND_TRACK_POS_LO,X
    INY
    LDA (SOUND_TRACK_PTR_LO),Y
    ADC SOUND_MUSIC_BASE_SAVED_HI
    STA SOUND_TRACK_POS_HI,X
    LDA #$00
    STA SOUND_LOOP_COUNT1,X
    STA SOUND_LOOP_COUNT2,X
    STA SOUND_PITCH_OFFSET,X
    LDA #$01
    STA SOUND_DURATION_LEFT,X
    LDA #$80
    STA SOUND_UPDATE_FLAGS,X
    LDA #$01
    STA SOUND_CHANNEL_FLAGS,X
    STA SOUND_PLAYING
    CPX #$04
    BCS @sfx_done
    STA SOUND_RELEASE_BEATS
    STA SOUND_RELEASE_BEATS_LEFT,X
@sfx_done:
    LDA #$FF
    STA SOUND_LOOP_END_LO,X
    STA SOUND_LOOP_END_HI,X
    INY
    BNE @loop
; 作用：写 APU_STATUS=$0F 打开四个声道，接着置播放标志
; 调用者：SOUND_PLAY_SONG、SOUND_START_TRACKS、SOUND_INIT_TRACKS
SOUND_ENABLE_APU:
    LDA #$0F
    STA APU_STATUS
; 作用：$0499 置位 7（有声音在播放）后返回
; 调用者：SOUND_PLAY_SONG、SOUND_START_TRACKS、SOUND_ENABLE_APU（顺序执行到这里）
SOUND_SET_ACTIVE_FLAG:
    LDA SOUND_FLAGS
    ORA #$80
    STA SOUND_FLAGS
    RTS
; 作用：关闭 APU，清 $039B 起的 256 字节声音状态，并写入默认值
; 调用者：SOUND_PLAY_SONG
SOUND_RESET:
    LDA #$00
    STA APU_STATUS
    STA SOUND_TRANSPOSE_GLOBAL
    LDX #$00
@loop:
    STA SOUND_MUSIC_BASE_LO,X
    INX
    BNE @loop
    LDA #$00
    STA SOUND_STATUS
    LDA #$8D
    STA SOUND_APU_STUB
    LDA #$40
    STA SOUND_APU_STUB+2
    LDA #$60
    STA SOUND_APU_STUB+3
    RTS
; 作用：功能 $12 子功能 $82：置位 $0630 的位 6，NMI 里据此调用 NMI_SOUND_UPDATE（用例 p04-sound-play.mjs）
; 调用者：SOUND_SUB_00、SOUND_SUB_01、SOUND_SUB_0A、SOUND_SUB_0B
SOUND_UPDATE_ON:
    LDA #$82
    STA SYS_SUBFUNCTION
    JSR API_12_PPU_CONTROL
    RTS
; 作用：功能 $12 子功能 $02：清除 $0630 的位 6，NMI 里不再调用 NMI_SOUND_UPDATE（用例 p04-sound-ctl.mjs）
; 调用者：SOUND_SUB_00、SOUND_SUB_01、SOUND_SUB_09、SOUND_SUB_0A、SOUND_SUB_0B
SOUND_UPDATE_OFF:
    LDA #$02
    STA SYS_SUBFUNCTION
    JSR API_12_PPU_CONTROL
    RTS
; 作用：子功能 9：同子功能 0，但最后不重新打开声音更新
; 调用者：SOUND_SUB_TABLE（地址表）
