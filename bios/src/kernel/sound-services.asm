SOUND_JUMP_SUB:
    JMP (GLYPH_ADDR_LO)
; 作用：声音服务 $65 的子功能表，14 项
; 引用者：API_65_SOUND_SERVICE
SOUND_SUB_TABLE:
    .word SOUND_SUB_00,SOUND_SUB_01,SOUND_SUB_02,SOUND_SUB_03,SOUND_SUB_04,SOUND_SUB_05,SOUND_SUB_06,SOUND_SUB_07
    .word SOUND_SUB_08,SOUND_SUB_09,SOUND_SUB_0A,SOUND_SUB_0B,SOUND_PLAY_WAV,SOUND_SUB_0D
; 作用：子功能 0：先关闭声音更新，再经功能 $2C 取出 SYS_GROUP 与 PROG_ENTRY 指向的音乐数据，先复位发声状态，再把指针当曲数据直接播放（$03A6 置 $FF）并播放曲号 $7F，$03A0 清 0，最后重新打开声音更新
; 调用者：SOUND_SUB_TABLE（地址表）
SOUND_SUB_00:
    JSR SOUND_UPDATE_OFF
    LDA #$2C
    STA SYS_FUNCTION
    JSR VEC_SYSCALL
    LDA FAR_OFFSET_HI
    ORA #$80
    STA PROG_ENTRY_HI
    LDA FAR_OFFSET_LO
    STA PROG_ENTRY_LO
    LDA SYS_PAGE
    STA SYS_GROUP
    LDA PROG_ENTRY_LO
    STA SOUND_TRACK_PTR_LO
    LDA PROG_ENTRY_HI
    STA SOUND_TRACK_PTR_HI
    LDA #$00
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
    LDA #$FF
    STA SOUND_SONG_PARAM
    LDA SYS_GROUP
    STA SOUND_MUSIC_PAGE
    LDA WINDOW_SAVE_0
    PHA
    LDA SOUND_MUSIC_PAGE
    STA WINDOW_SAVE_0
    JSR MAP_WINDOWS_8000
    LDA #$7F
    STA SOUND_NEXT_SONG
    JSR SOUND_PLAY_SONG
    PLA
    STA WINDOW_SAVE_0
    JSR MAP_WINDOWS_8000
    LDA #$00
    STA SOUND_REPLAY
    JSR SOUND_UPDATE_ON
    RTS
; 作用：子功能 1：流程同子功能 0，区别是 $03A0 置 $FF
; 调用者：SOUND_SUB_TABLE（地址表）
