PLAY_SAMPLE_LO:
    LDA #$A2
; 作用：设好 $4035 的采样速率后：用功能 $2C 取得 WAV 数据位置，加 $2C 越过文件头
; 调用者：SOUND_PLAY_WAV、PLAY_SAMPLE_HI、PLAY_SAMPLE_LO（顺序执行到这里）
PLAY_SAMPLE_START:
    STA TIMER_COUNT
    LDA #$2C
    STA SYS_FUNCTION
    JSR VEC_SYSCALL
    CLC
    LDA FAR_OFFSET_LO
    ADC #$2C
    STA FAR_OFFSET_LO
