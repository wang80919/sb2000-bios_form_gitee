SOUND_SUB_0D:
    LDA SYS_ARG_0F
    BEQ @done
    LDX #$05
    LDA #$1B
    STA SYS_FUNCTION
    JSR VEC_SYSCALL
@loop:
    JSR SOUND_PLAY_WAV
    DEC SYS_ARG_0F
    BNE @loop
@done:
    LDA #$FF
    STA APU_STATUS
    RTS
