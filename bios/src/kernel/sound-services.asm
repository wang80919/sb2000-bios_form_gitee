; 作用：声音服务 $65/$0C：播放内存里的 WAV
; 入口：SYS_GROUP（$0642）与 PROG_ENTRY（$0C/$0D）指向 WAV 文件头，经功能 $2C 换成远指针
; 从文件头偏移 $28 取 4 字节采样数据长度，偏移 $18 的采样率低字节选速度（$44 为 44100 Hz，$22 为 22050 Hz，其他按 11025 Hz），跳过 44 字节文件头，把采样逐字节写到 DAC 寄存器 $4027，定时器 $4034/$4035 控制节拍
; 调用者：SOUND_SUB_TABLE（地址表）、SOUND_SUB_0D
SOUND_PLAY_WAV:
    LDA PROG_ENTRY_LO
    PHA
    LDA PROG_ENTRY_HI
    PHA
