; 功能 $7B-$7D 的入口：清 DOS_ERROR，按功能号减 $7B 转 FS_DISPATCH_7B、FS_DISPATCH_7C、FS_DISPATCH_7D
; 调用者：fs-open-and-io.asm 开头的入口代码
FS_DISPATCH:
    LDA #$00
    STA DOS_ERROR
    SEC
    LDA SYS_FUNCTION
    SBC #$7B
    JSR FS_INLINE_JUMP
    .word FS_DISPATCH_7B,FS_DISPATCH_7C,FS_DISPATCH_7D
; 作用：功能 $7B：子功能 0-$13 按表跳转，超出转 FS_BAD_SUBFUNCTION
; 调用者：FS_DISPATCH（地址表）
FS_DISPATCH_7B:
    LDA #$13
    CMP SYS_SUBFUNCTION
    BCS @dispatch
    JMP FS_BAD_SUBFUNCTION
@dispatch:
    LDA SYS_SUBFUNCTION
    JSR FS_INLINE_JUMP
    .word FS_NEXT_SECTOR,FS_FAT_LOAD,FS_FAT_STORE,FS_CLUSTER_TO_LBA,FS_CLUSTER_INC,FS_FAT_GET,FS_FREE_SPACE,FS_FAT_CACHE_RESET
    .word FS_SEEK_SECTOR,FS_OPEN,FS_CLOSE,FS_FIND_ENTRY,FS_ALLOC_FOR_SIZE,FS_SIZE_TO_UNITS,FS_TRANSFER_CHAIN,FS_FAT_SET
    .word FS_FAT_WRITE_BACK,FS_LBA_TO_CHS,FS_OPEN_MODE3_CLOSE_NOFLUSH,FS_RESET_HANDLES
; 作用：功能 $7C：子功能 0-$10 按表跳转，超出转 FS_BAD_SUBFUNCTION
; 调用者：FS_DISPATCH（地址表）
FS_DISPATCH_7C:
    LDA #$10
    CMP SYS_SUBFUNCTION
    BCS @dispatch
    JMP FS_BAD_SUBFUNCTION
@dispatch:
    LDA SYS_SUBFUNCTION
    JSR FS_INLINE_JUMP
    .word FS_OPEN_CALL,FS_OPEN_MODE1,FS_CLOSE_FLUSH,FS_OPEN_MODE3_CLOSE,FS_RENAME,FS_READ_AT,FS_WRITE_AT,FS_SET_DATE
    .word FS_GET_DATE,FS_SET_TIME,FS_GET_TIME,FS_SET_ATTR,FS_GET_ATTR,FS_GET_SIZE,FS_READ_BOOT_SECTOR,FS_READ_FILE
    .word FS_WRITE_FILE
; 作用：功能 $7D：子功能 0-3 按表跳转，超出转 FS_BAD_SUBFUNCTION
; 调用者：FS_DISPATCH（地址表）
FS_DISPATCH_7D:
    LDA #$03
    CMP SYS_SUBFUNCTION
    BCS @dispatch
    JMP FS_BAD_SUBFUNCTION
@dispatch:
    LDA SYS_SUBFUNCTION
    JSR FS_INLINE_JUMP
    .word FS_FIND_ENTRY_FLUSH,FS_FORMAT_NAME,FS_MAKE_DIR,FS_REMOVE_DIR
; 作用：子功能号无效：DOS_ERROR=1，C=1 返回
; 调用者：FS_DISPATCH_7B、FS_DISPATCH_7C、FS_DISPATCH_7D
FS_BAD_SUBFUNCTION:
    LDA #$01
    STA DOS_ERROR
    SEC
    RTS
; 作用：页内的内联跳转表（与页组 0 的同名功能相同）：返回地址后面跟 16 位地址表，按 A 取项并跳转。
; 输入：A=表项序号。
; 调用者：FS_DISPATCH、FS_DISPATCH_7B、FS_DISPATCH_7C、FS_DISPATCH_7D
FS_INLINE_JUMP:
    ASL A
    TAY
    PLA
    STA CALL_VEC_LO
    PLA
    STA CALL_VEC_HI
    INY
    LDA (CALL_VEC_LO),Y
    PHA
    INY
